from ultralytics import YOLO


def main():

    # ========================================================
    # 1. Build YOLOv8s-P2-Gate
    # ========================================================

    model = YOLO("yolov8s-p2-gate.yaml")


    # ========================================================
    # 2. Transfer YOLOv8s COCO pretrained weights
    # ========================================================

    model.load("yolov8s.pt")


    # ========================================================
    # 3. Train on VisDrone
    # ========================================================

    results = model.train(

        data="VisDrone.yaml",

        # ----------------------------------------------------
        # Core experiment settings
        # ----------------------------------------------------

        imgsz=960,

        epochs=150,

        batch=6,

        device=0,

        workers=8,


        # ----------------------------------------------------
        # Optimization
        # ----------------------------------------------------

        optimizer="auto",

        amp=True,

        pretrained=True,


        # ----------------------------------------------------
        # Data loading
        # ----------------------------------------------------

        cache=False,


        # ----------------------------------------------------
        # Augmentation
        # ----------------------------------------------------

        close_mosaic=10,


        # ----------------------------------------------------
        # Early stopping
        # Formal ablation: effectively train full 150 epochs
        # ----------------------------------------------------

        patience=150,


        # ----------------------------------------------------
        # Reproducibility
        # ----------------------------------------------------

        seed=0,

        deterministic=True,


        # ----------------------------------------------------
        # Output
        # ----------------------------------------------------

        project="/root/rivermind-data/yolo/ultralytics-main/runs/detect",

        name="v8s_p2_gate_960_batch6_150e",
    )


if __name__ == "__main__":
    main()